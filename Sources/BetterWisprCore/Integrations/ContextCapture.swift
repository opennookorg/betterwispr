import AppKit
import ApplicationServices
import Carbon
import ScreenCaptureKit
import Vision

extension DictationContext {
    static let secretTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType")
    ]

    /// Starts reading the selection, window text and, when asked, clipboard of `app`; reads nothing while secure input is on.
    @MainActor
    public static func capture(from app: NSRunningApplication, recognizingScreen: Bool, readingClipboard: Bool) -> Task<DictationContext, Never> {
        guard !IsSecureEventInputEnabled() else { return Task { DictationContext() } }
        let clipboard = readingClipboard ? clipboardText(.general) : nil
        let pid = app.processIdentifier, name = app.localizedName
        guard pid != ProcessInfo.processInfo.processIdentifier, AXIsProcessTrusted() else { return Task { DictationContext(clipboard: clipboard) } }
        let screen = recognizingScreen && CGPreflightScreenCaptureAccess()
        return Task.detached(priority: .userInitiated) {
            let element = AXUIElementCreateApplication(pid)
            AXUIElementSetMessagingTimeout(element, 0.25)
            let selected = element.selectedText
            guard let window = element.element(kAXFocusedWindowAttribute) else { return DictationContext(selectedText: selected, clipboard: clipboard) }
            let title = window.string(kAXTitleAttribute), frame = window.frame
            var text = accessibilityText(of: window)
            if screen, text.count < 200, let recognized = await Task(operation: { await recognizedText(pid: pid, frame: frame, title: title) }).value(within: .seconds(3)) ?? nil,
               recognized.count > text.count {
                text = recognized
            }
            let content = text.isEmpty ? nil : "Active Window: \(title ?? name ?? "Unknown")\nApplication: \(name ?? "Unknown")\n\nWindow Content:\n\(text)"
            return DictationContext(selectedText: selected, clipboard: clipboard, window: content)
        }
    }

    /// The text selected in `app`; nil while secure input is on, without Accessibility, or for this app.
    @MainActor
    public static func selectedText(in app: NSRunningApplication) async -> String? {
        let pid = app.processIdentifier
        guard !IsSecureEventInputEnabled(), AXIsProcessTrusted(), pid != ProcessInfo.processInfo.processIdentifier else { return nil }
        return await Task.detached(priority: .userInitiated) {
            let element = AXUIElementCreateApplication(pid)
            AXUIElementSetMessagingTimeout(element, 0.25)
            return element.selectedText
        }.value
    }

    /// The mixed-case names on screen and those macOS English spell checking does not know, for Parakeet to spell.
    @MainActor
    public func spellingTerms() -> [String] {
        spellingTerms(isKnownWord: ParakeetProvider.isSpelledCorrectly)
    }

    /// The clipboard's plain text, or nil when a password manager or another app marked it secret or temporary.
    static func clipboardText(_ pasteboard: NSPasteboard) -> String? {
        guard let types = pasteboard.types, !types.contains(where: secretTypes.contains) else { return nil }
        return pasteboard.string(forType: .string)
    }

    /// Collects text values from the window's accessibility tree in reading order, skipping secure fields, within a node and time budget.
    private static func accessibilityText(of window: AXUIElement) -> String {
        let deadline = ContinuousClock.now + .seconds(1)
        let attributes = [kAXSubroleAttribute, kAXValueAttribute, kAXChildrenAttribute] as CFArray
        var pending = [window], lines: [String] = [], length = 0, visited = 0
        while let element = pending.popLast(), visited < 3_000, length < 4_000, ContinuousClock.now < deadline {
            visited += 1
            AXUIElementSetMessagingTimeout(element, 0.25)
            var copied: CFArray?
            guard AXUIElementCopyMultipleAttributeValues(element, attributes, [], &copied) == .success,
                  let values = copied as? [AnyObject], values.count == 3, values[0] as? String != kAXSecureTextFieldSubrole else { continue }
            if let text = (values[1] as? String)?.trimmingCharacters(in: .whitespacesAndNewlines), !text.isEmpty {
                lines.append(text)
                length += text.count + 1
            }
            if let children = values[2] as? [AXUIElement] { pending.append(contentsOf: children.reversed()) }
        }
        return lines.joined(separator: "\n")
    }

    /// Reads the app's focused window pixels with Vision, matching it by frame and then title.
    private static func recognizedText(pid: pid_t, frame: CGRect?, title: String?) async -> String? {
        guard let content = try? await SCShareableContent.excludingDesktopWindows(false, onScreenWindowsOnly: true) else { return nil }
        let windows = content.windows.filter {
            $0.owningApplication?.processID == pid && $0.windowLayer == 0 && $0.isOnScreen && $0.frame.width > 0 && $0.frame.height > 0
        }
        func distance(_ window: SCWindow) -> CGFloat {
            guard let frame else { return .infinity }
            return abs(window.frame.minX - frame.minX) + abs(window.frame.minY - frame.minY) + abs(window.frame.width - frame.width) + abs(window.frame.height - frame.height)
        }
        let nearest = windows.min { distance($0) < distance($1) }.flatMap { distance($0) <= 96 ? $0 : nil }
        guard let window = nearest ?? windows.first(where: { title != nil && $0.title == title }) ?? windows.first else { return nil }
        let configuration = SCStreamConfiguration()
        let scale = min(2, 2_800 / max(window.frame.width, window.frame.height))
        configuration.width = max(1, Int(window.frame.width * scale))
        configuration.height = max(1, Int(window.frame.height * scale))
        guard let image = try? await SCScreenshotManager.captureImage(contentFilter: SCContentFilter(desktopIndependentWindow: window), configuration: configuration) else { return nil }
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.usesLanguageCorrection = true
        request.automaticallyDetectsLanguage = true
        try? VNImageRequestHandler(cgImage: image, options: [:]).perform([request])
        return request.results?.compactMap { $0.topCandidates(1).first?.string }.joined(separator: "\n")
    }
}
